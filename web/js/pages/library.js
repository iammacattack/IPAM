// --------------------------------------------------------------------------- VLAN dialogs

async function vlanDialog(v, refresh) {
  const isNew = !v;
  const k = input({ value: v?.vlanKey || '', class: 'mono', placeholder: 'e.g. DCS-CCTV', disabled: !isNew });
  const id = input({ type: 'number', min: 2, max: 4094, value: v?.vlanId ?? '' });
  const name = input({ class: 'mono', value: v?.vlanName || '', placeholder: 'e.g. v2040-CCTV' });
  const aliases = input({ class: 'mono', value: (v?.aliases || []).join(', '), placeholder: 'comma separated, optional' });
  const cls = input({ class: 'mono', value: v?.class || '', placeholder: 'CORP, DCS, CSMS…' });
  const zone = select(ZONES, v?.securityZone || '');
  const status = select(['active', 'deprecated'], v?.status || 'active');
  const desc = input({ class: 'wide', value: v?.description || '' });
  const out = h('div');
  const ok = await modal({
    title: isNew ? 'Add VLAN' : `Edit ${v.vlanKey}`,
    body: h('div', {},
      h('div', { class: 'form-grid' },
        field('Key', k, isNew ? 'UPPER-KEBAB, unique, can\'t change later' : 'The key never changes'),
        field('VLAN ID', id, isNew ? null : 'Frozen while a live site carries this VLAN'),
        field('Name', name, 'Unique'), field('Aliases', aliases, 'Other names lookups accept'),
        field('Class', cls), field('Security zone', zone), isNew ? null : field('Status', status, 'Deprecated VLANs can\'t be added to new template releases'), field('Description', desc)),
      out),
    actions: [{ label: 'Cancel', value: false }, {
      label: isNew ? 'Add' : 'Save', kind: 'primary', value: true,
      validate: saver(out, () => (isNew
        ? post('/vlans', { vlanKey: k.value.trim().toUpperCase(), vlanId: id.value ? Number(id.value) : null, vlanName: name.value.trim(),
          aliases: list(aliases.value), class: cls.value.trim() || null, securityZone: zone.value || null, description: desc.value || null })
        : patch(`/vlans/${encodeURIComponent(v.vlanKey)}`, {
          vlanId: id.value ? Number(id.value) : null, clearVlanId: !id.value, vlanName: name.value.trim(), aliases: list(aliases.value),
          class: cls.value.trim(), securityZone: zone.value, status: status.value, description: desc.value }))),
    }],
  });
  if (ok) { toast(isNew ? 'VLAN added' : 'VLAN saved', 'success'); refresh(); }
}

function usageBody(u) {
  const section = (title, items) => (items.length ? [h('h3', {}, title), h('div', { class: 'chips' }, items)] : []);
  return h('div', {},
    !u.inUse ? h('p', {}, 'Nothing uses it.') : null,
    ...section('Template versions', (u.templates || []).map((t) => chip(`${t.template} · ${t.state}`, t.state))),
    ...section('Live sites', (u.sites || []).map((s) => (typeof s === 'string' ? chip(s, 'draft') : chip(`${s.site_code} · ${s.status}`, s.status)))),
    ...section('Host pools', (u.hostPools || []).map((p) => chip(p, 'draft'))),
    ...section('Address pools', (u.pools || []).map((p) => chip(p, 'draft'))),
    u.blocks ? h('p', {}, `${u.blocks} block(s) and ${u.subnets} subnet(s) are in it.`) : null);
}

async function vlanUsage(v) {
  const u = await get(`/vlans/${encodeURIComponent(v.vlanKey)}/usage`);
  modal({ title: `Where ${v.vlanKey} is used`, body: usageBody(u) });
}

async function deleteVlan(v, refresh) {
  if (!(await confirmBox(`Delete ${v.vlanKey}`, `Delete VLAN ${v.vlanKey} (${v.vlanName}) from the library?`, 'Delete', 'danger'))) return;
  try {
    await del(`/vlans/${encodeURIComponent(v.vlanKey)}`);
    toast(`${v.vlanKey} deleted`, 'success');
    refresh();
  } catch (err) {
    if (err.code !== 'IPAM-VLAN-IN-USE') { modal({ title: 'Couldn\'t delete', body: errorPanel(err) }); return; }
    const choice = await modal({
      title: `${v.vlanKey} is in use`,
      body: h('div', {}, h('p', {}, 'It can\'t be deleted while these use it. You can deprecate it instead: it stays where it\'s used, but can\'t go into new template releases.'), usageBody(err.body.usage)),
      actions: [{ label: 'Close', value: false }, v.status === 'deprecated' ? null : { label: 'Deprecate instead', kind: 'primary', value: true }].filter(Boolean),
    });
    if (choice) {
      try { await patch(`/vlans/${encodeURIComponent(v.vlanKey)}`, { status: 'deprecated' }); toast(`${v.vlanKey} deprecated`, 'success'); refresh(); } catch (e2) { modal({ title: 'Couldn\'t deprecate', body: errorPanel(e2) }); }
    }
  }
}

// --------------------------------------------------------------------------- host pool dialogs

function vlanPicker(initial) {
  const chosen = [...initial];
  const box = h('div', { class: 'chips' });
  const entry = input({ list: 'dl-lib-vlans', class: 'mono', placeholder: 'type a VLAN key…' });
  const draw = () => mount(box, chosen.length ? chosen.map((k) => h('span', { class: 'chip chip-draft' }, k, ' ',
    h('button', { type: 'button', class: 'btn-link', 'aria-label': `Remove ${k}`, onClick: () => { chosen.splice(chosen.indexOf(k), 1); draw(); } }, '✕'))) : h('span', { class: 'muted small' }, 'No VLANs yet'));
  const add = () => {
    const k = entry.value.trim().toUpperCase();
    if (k && !chosen.includes(k)) chosen.push(k);
    entry.value = '';
    draw();
  };
  entry.addEventListener('keydown', (e) => { if (e.key === 'Enter') { e.preventDefault(); add(); } });
  entry.addEventListener('change', add);
  draw();
  return { el: h('div', {}, box, h('div', { class: 'inline' }, entry, button('Add', add, 'small'))), values: () => chosen };
}

