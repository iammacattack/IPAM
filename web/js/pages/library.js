// Library: VLANs, host pools, address pools, VRFs - full add / change / delete (MACD).
// The server refuses deletes while anything uses an item, and says what; the UI shows that list.
import { get, post, patch, api, errorPanel } from '../api.js';
import { h, mount, table, tabs, button, input, select, field, modal, confirmBox, toast, chip, datalist } from '../dom.js';
import { can } from '../session.js';

const ZONES = ['', 'Internal', 'DataCentre', 'DMZ', 'OOB', 'Perimeter'];
const del = (path, query) => api('DELETE', path, { query });
const put = (path, body) => api('PUT', path, { body });

export async function render(root, active = 'vlans') {
  const body = h('div');
  const bar = h('div');
  const show = async (id) => {
    active = id;
    mount(bar, tabs([
      { id: 'vlans', label: 'VLAN library' }, { id: 'roles', label: 'Host pools' }, { id: 'pools', label: 'Address pools' }, { id: 'vrfs', label: 'VRFs' },
    ], active, show));
    mount(body, h('p', { class: 'muted' }, 'Loading…'));
    try { mount(body, await VIEWS[id](() => show(id))); } catch (err) { mount(body, errorPanel(err)); }
  };
  mount(root, h('h1', {}, 'Library'),
    h('p', { class: 'page-sub' }, 'The configuration every template and site draws on. Changes are audited, and never move addresses already held at sites.'),
    h('div', { class: 'card' }, bar, body));
  show(active);
}

/** Run a save; show the server's answer inside the dialog if it refuses. */
function saver(out, fn) {
  return async () => {
    try { await fn(); return true; } catch (err) { mount(out, errorPanel(err)); return false; }
  };
}

function rowActions(...buttons) {
  return h('div', { class: 'actions nowrap' }, buttons.filter(Boolean));
}

function list(raw) {
  return raw.split(/[\s,]+/).map((s) => s.trim()).filter(Boolean);
}

